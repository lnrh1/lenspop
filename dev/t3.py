import io
NL = chr(10)
p = 'src/Program.cs'
s = io.open(p, encoding='utf-8').read()
old = []
old.append('        public static void LogLine(string s)')
old.append('        {')
old.append('            try')
old.append('            {')
old.append('                string p = System.IO.Path.Combine(AppConfig.Dir, "debug.log");')
old.append('                var fi = new System.IO.FileInfo(p);')
old.append('                if (fi.Exists && fi.Length > 128 * 1024) System.IO.File.Delete(p);')
old.append('                System.IO.File.AppendAllText(p, DateTime.Now.ToString("HH:mm:ss.fff") + "  " + s + "\\r\\n");')
old.append('            }')
old.append('            catch { }')
old.append('        }')
old = NL.join(old)
new = []
new.append('        public static void LogLine(string s)')
new.append('        {')
new.append('            string line = DateTime.Now.ToString("HH:mm:ss.fff") + "  " + s + "\\r\\n";')
new.append('            try')
new.append('            {')
new.append('                string p = System.IO.Path.Combine(AppConfig.Dir, "debug.log");')
new.append('                var fi = new System.IO.FileInfo(p);')
new.append('                if (fi.Exists && fi.Length > 128 * 1024) System.IO.File.Delete(p);')
new.append('                System.IO.File.AppendAllText(p, line);')
new.append('                return;')
new.append('            }')
new.append('            catch { }')
new.append('            try { System.IO.File.AppendAllText(System.IO.Path.Combine(System.IO.Path.GetTempPath(), "LensPop-debug.log"), line); } catch { }')
new.append('        }')
new = NL.join(new)
if old in s:
    s = s.replace(old, new, 1)
    io.open(p, 'w', encoding='utf-8', newline=chr(13)+chr(10)).write(s)
    print('logline ok')
else:
    print('missing')